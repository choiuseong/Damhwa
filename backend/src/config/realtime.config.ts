/** 세션을 열 때마다 현재 한국 시각을 덧붙여서 "내일", "다음 주" 같은 표현을 정확히 계산하게 한다 */
export function buildInstructions(now = new Date()): string {
  const kst = new Intl.DateTimeFormat("ko-KR", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "long",
    day: "numeric",
    weekday: "long",
    hour: "numeric",
    minute: "2-digit",
  }).format(now);

  return `${realtimeConfig.instructions}
# 현재 시각
지금은 한국 시간으로 ${kst}이에요. 일정 시각은 +09:00 시간대의 ISO 8601 형식으로 등록해요.`;
}
